    private void bCreCliActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bCreCliActionPerformed
        String nombre = tNom.getText();
        int numero = Integer.parseInt(tNum.getText());
        float puntos = Float.parseFloat(tPun.getText());
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("yyyy, mm, dd");
        LocalDate fecNac = LocalDate.parse(tFecNac.getText(), formatter);

        if(numero <= 0 || nombre.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, completa los campos obligatorios.");
            return;
        }

        Cliente nuevoCliente = new Cliente(numero, nombre, puntos, fecNac);
        VistaClientes.listaClientes.añadirCliente(nuevoCliente);

        JOptionPane.showMessageDialog(this, "¡Cliente guardado con éxito!");
        
        // Limpiar campos
        tNom.setText("");
        tNum.setText("");
        tFecNac.setText("");
        tPun.setText("");
    }//GEN-LAST:event_bCreCliActionPerformed


